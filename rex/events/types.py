"""Core domain event taxonomy and structured frames for Trust & Safety incidents."""

from dataclasses import dataclass, field
from datetime import datetime, timezone
from enum import Enum
import json
from typing import Any, Dict, List, Union


class EventType(str, Enum):
    """Representative Domain Event Tokens for typical Trust & Safety incident groups."""
    CREDENTIAL_STUFFING = "<TYPE_CREDENTIAL_STUFFING>"
    ACCOUNT_TAKEOVER = "<TYPE_ACCOUNT_TAKEOVER>"
    PROMO_ABUSE = "<TYPE_PROMO_ABUSE>"
    API_SCRAPING = "<TYPE_API_SCRAPING>"
    PAYMENT_FRAUD = "<TYPE_PAYMENT_FRAUD>"
    BENIGN = "<TYPE_BENIGN>"
    UNKNOWN = "<TYPE_UNKNOWN>"


# Registered domain event tokens
ALL_EVENT_TOKENS: List[str] = [t.value for t in EventType]


@dataclass
class SecurityEventFrame:
    """Standardized event envelope generated by the parser."""
    event_type: EventType
    confidence: float
    source: str
    raw_payload: Union[Dict[str, Any], str]
    attributes: Dict[str, Any] = field(default_factory=dict)
    matched_rules: List[str] = field(default_factory=list)
    timestamp: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

    @property
    def context_token(self) -> str:
        return self.event_type.value

    def to_state(self) -> Dict[str, Any]:
        """Convert the frame into a state dictionary."""
        attrs_clean = {k: v for k, v in self.attributes.items() if v is not None}
        return {
            "type_token": self.context_token,
            "source": self.source,
            "confidence": self.confidence,
            "attributes": attrs_clean,
            "payload_summary": (
                json.dumps(self.raw_payload, ensure_ascii=False)
                if isinstance(self.raw_payload, (dict, list))
                else str(self.raw_payload)
            ),
        }

    def to_routing_text(self) -> str:
        """Create a prefixed routing text using the domain token."""
        raw_str = (
            json.dumps(self.raw_payload, ensure_ascii=False)
            if isinstance(self.raw_payload, (dict, list))
            else str(self.raw_payload)
        )
        return f"{self.context_token} [SRC:{self.source}] [CONF:{self.confidence:.2f}] {raw_str}"
